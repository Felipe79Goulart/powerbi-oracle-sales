    V.NOME_VENDEDOR AS SALES_REP_NAME,
    V.EQUIPE_EN_US AS SALES_TEAM,
    V.GERENTE AS MANAGER_NAME,
    V.REGIAO_EN_US AS SALES_REGION,
    V.META_MENSAL AS MONTHLY_TARGET,

    COUNT(DISTINCT F.PEDIDO_ID) AS ORDER_COUNT,
    COUNT(DISTINCT F.CLIENTE_SK) AS CUSTOMERS_SERVED,
    SUM(F.QUANTIDADE) AS QUANTITY_SOLD,

    ROUND(SUM(F.VALOR_LIQUIDO), 2)
        AS NET_SALES,

    ROUND(SUM(F.LUCRO), 2)
        AS TOTAL_PROFIT,

    ROUND(
        SUM(F.LUCRO)
        / NULLIF(SUM(F.VALOR_LIQUIDO), 0)
        * 100,
        2
    ) AS PROFIT_MARGIN_PCT,

    ROUND(
        SUM(F.VALOR_LIQUIDO)
        / NULLIF(COUNT(DISTINCT F.PEDIDO_ID), 0),
        2
    ) AS AVERAGE_ORDER_VALUE,

    ROUND(
        SUM(F.VALOR_LIQUIDO)
        / NULLIF(V.META_MENSAL, 0)
        * 100,
        2
    ) AS TARGET_ACHIEVEMENT_PCT,

    ROUND(
        SUM(F.VALOR_LIQUIDO) - V.META_MENSAL,
        2
    ) AS TARGET_DIFFERENCE,

    CASE
        WHEN SUM(F.VALOR_LIQUIDO) >= V.META_MENSAL
        THEN 'Target achieved'
        ELSE 'Target not achieved'
    END AS TARGET_STATUS

FROM FATO_VENDAS F

INNER JOIN DIM_TEMPO T
    ON T.TEMPO_SK = F.TEMPO_SK

INNER JOIN DIM_VENDEDOR V
    ON V.VENDEDOR_SK = F.VENDEDOR_SK

INNER JOIN DIM_STATUS_VENDA S
    ON S.STATUS_VENDA_SK = F.STATUS_VENDA_SK

WHERE S.STATUS_VENDA_CODIGO IN (
    'INVOICED',
    'DELIVERED'
)

GROUP BY
    T.ANO,
    T.MES_NUMERO,
    T.NOME_MES_EN_US,
    T.ANO_MES,
    V.VENDEDOR_SK,
    V.VENDEDOR_ID,
    V.NOME_VENDEDOR,
    V.EQUIPE_EN_US,
    V.GERENTE,
    V.REGIAO_EN_US,
    V.META_MENSAL;

