    T.ANO_MES,
    T.TRIMESTRE,
    T.NOME_TRIMESTRE_PT_BR AS NOME_TRIMESTRE,

    COUNT(DISTINCT F.PEDIDO_ID) AS QUANTIDADE_PEDIDOS,
    COUNT(*) AS QUANTIDADE_ITENS_PEDIDO,
    SUM(F.QUANTIDADE) AS QUANTIDADE_VENDIDA,

    ROUND(
        SUM(F.VALOR_BRUTO),
        2
    ) AS FATURAMENTO_BRUTO,

    ROUND(
        SUM(F.VALOR_DESCONTO),
        2
    ) AS TOTAL_DESCONTOS,

    ROUND(
        SUM(F.VALOR_LIQUIDO),
        2
    ) AS FATURAMENTO_LIQUIDO,

    ROUND(
        SUM(F.CUSTO_TOTAL),
        2
    ) AS CUSTO_TOTAL,

    ROUND(
        SUM(F.LUCRO),
        2
    ) AS LUCRO_TOTAL,

    ROUND(
        SUM(F.LUCRO)
        / NULLIF(SUM(F.VALOR_LIQUIDO), 0)
        * 100,
        2
    ) AS MARGEM_LUCRO_PCT,

    ROUND(
        SUM(F.VALOR_LIQUIDO)
        / NULLIF(COUNT(DISTINCT F.PEDIDO_ID), 0),
        2
    ) AS TICKET_MEDIO

FROM FATO_VENDAS F

INNER JOIN DIM_TEMPO T
    ON T.TEMPO_SK = F.TEMPO_SK

INNER JOIN DIM_STATUS_VENDA S
    ON S.STATUS_VENDA_SK = F.STATUS_VENDA_SK

WHERE S.STATUS_VENDA_CODIGO IN (
    'INVOICED',
    'DELIVERED'
)

