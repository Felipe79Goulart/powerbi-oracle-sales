/* ======================================================
DIMENSÃO: TEMPO (PT-EN)
=======================================================*/

CREATE TABLE DIM_TEMPO (
    TEMPO_SK                   NUMBER(8)       NOT NULL,
    DATA_COMPLETA              DATE            NOT NULL,
    DIA_MES                    NUMBER(2)       NOT NULL,
    DIA_SEMANA                 NUMBER(1)       NOT NULL,

    NOME_DIA_SEMANA_PT_BR      VARCHAR2(20)    NOT NULL,
    NOME_DIA_SEMANA_EN_US      VARCHAR2(20)    NOT NULL,

    SEMANA_ANO                 NUMBER(2)       NOT NULL,
    MES_NUMERO                 NUMBER(2)       NOT NULL,

    NOME_MES_PT_BR             VARCHAR2(20)    NOT NULL,
    NOME_MES_EN_US             VARCHAR2(20)    NOT NULL,

    TRIMESTRE                  NUMBER(1)       NOT NULL,
    NOME_TRIMESTRE_PT_BR       VARCHAR2(20)    NOT NULL,
    NOME_TRIMESTRE_EN_US       VARCHAR2(20)    NOT NULL,

    ANO                        NUMBER(4)        NOT NULL,
    ANO_MES                    VARCHAR2(7)      NOT NULL,
    ANO_TRIMESTRE              VARCHAR2(7)      NOT NULL,

    FIM_DE_SEMANA              CHAR(1)          NOT NULL,

    CONSTRAINT PK_DIM_TEMPO
        PRIMARY KEY (TEMPO_SK),

    CONSTRAINT UK_DIM_TEMPO_DATA
        UNIQUE (DATA_COMPLETA),

    CONSTRAINT CK_DIM_TEMPO_DIA_SEMANA
        CHECK (DIA_SEMANA BETWEEN 1 AND 7),

    CONSTRAINT CK_DIM_TEMPO_MES
        CHECK (MES_NUMERO BETWEEN 1 AND 12),

    CONSTRAINT CK_DIM_TEMPO_TRIMESTRE
        CHECK (TRIMESTRE BETWEEN 1 AND 4),

    CONSTRAINT CK_DIM_TEMPO_FDS
        CHECK (FIM_DE_SEMANA IN ('S', 'N'))
);


/* ======================================================
DIMENSÃO: CLIENTE (PT-EN)
=======================================================*/

CREATE TABLE DIM_CLIENTE (
    CLIENTE_SK             NUMBER
                           GENERATED BY DEFAULT ON NULL AS IDENTITY,

    CLIENTE_ID             VARCHAR2(20)     NOT NULL,
    NOME_CLIENTE           VARCHAR2(150)    NOT NULL,
    TIPO_PESSOA            CHAR(2)          DEFAULT 'PF' NOT NULL,

    SEGMENTO_CODIGO        VARCHAR2(30)     NOT NULL,
    SEGMENTO_PT_BR         VARCHAR2(50)     NOT NULL,
    SEGMENTO_EN_US         VARCHAR2(50)     NOT NULL,

    EMAIL                  VARCHAR2(150),
    CIDADE                 VARCHAR2(100),
    ESTADO                 VARCHAR2(2),

    REGIAO_CODIGO          VARCHAR2(30)     NOT NULL,
    REGIAO_PT_BR           VARCHAR2(30)     NOT NULL,
    REGIAO_EN_US           VARCHAR2(30)     NOT NULL,

    PAIS_CODIGO            VARCHAR2(3)      DEFAULT 'BRA' NOT NULL,
    PAIS_PT_BR             VARCHAR2(50)     DEFAULT 'Brasil' NOT NULL,
    PAIS_EN_US             VARCHAR2(50)     DEFAULT 'Brazil' NOT NULL,

    DATA_CADASTRO          DATE,
    ATIVO                  CHAR(1)          DEFAULT 'S' NOT NULL,
    DATA_INICIO            DATE             DEFAULT DATE '2024-01-01',
    DATA_FIM               DATE             DEFAULT DATE '9999-12-31',
    REGISTRO_ATUAL         CHAR(1)          DEFAULT 'S' NOT NULL,

    CONSTRAINT PK_DIM_CLIENTE
        PRIMARY KEY (CLIENTE_SK),

    CONSTRAINT UK_DIM_CLIENTE
        UNIQUE (CLIENTE_ID),

    CONSTRAINT CK_DIM_CLIENTE_ATIVO
        CHECK (ATIVO IN ('S', 'N')),

    CONSTRAINT CK_DIM_CLIENTE_ATUAL
        CHECK (REGISTRO_ATUAL IN ('S', 'N')),

    CONSTRAINT CK_DIM_CLIENTE_TIPO
        CHECK (TIPO_PESSOA IN ('PF', 'PJ')),

    CONSTRAINT CK_DIM_CLIENTE_DATAS
        CHECK (DATA_FIM >= DATA_INICIO)
);

