/* ============================================================
   TABELA FATO: VENDAS

   GRANULARIDADE:
   Uma linha por item vendido dentro de um pedido.

   OBSERVAÇÃO SOBRE IDIOMAS:
   A tabela fato não armazena traduções. Os atributos
   traduzíveis ficam armazenados nas respectivas dimensões.
   ============================================================ */

CREATE TABLE FATO_VENDAS (
    VENDA_SK            NUMBER
                        GENERATED BY DEFAULT ON NULL AS IDENTITY,

    PEDIDO_ID           VARCHAR2(30)     NOT NULL,
    ITEM_PEDIDO         NUMBER(5)        NOT NULL,

    TEMPO_SK            NUMBER(8)        NOT NULL,
    CLIENTE_SK          NUMBER           NOT NULL,
    PRODUTO_SK          NUMBER           NOT NULL,
    VENDEDOR_SK         NUMBER           NOT NULL,
    CANAL_SK            NUMBER           NOT NULL,
    STATUS_VENDA_SK     NUMBER(2)        NOT NULL,

    QUANTIDADE          NUMBER(10)       NOT NULL,
    PRECO_UNITARIO      NUMBER(14,2)     NOT NULL,
    DESCONTO_PCT        NUMBER(5,2)      DEFAULT 0 NOT NULL,
    VALOR_BRUTO         NUMBER(16,2)     NOT NULL,
    VALOR_DESCONTO      NUMBER(16,2)     DEFAULT 0 NOT NULL,
    VALOR_LIQUIDO       NUMBER(16,2)     NOT NULL,
    CUSTO_TOTAL         NUMBER(16,2)     NOT NULL,
    LUCRO               NUMBER(16,2)     NOT NULL,

    MARGEM_PCT NUMBER(8,2)
        GENERATED ALWAYS AS (
            CASE
                WHEN VALOR_LIQUIDO <> 0
                THEN ROUND(
                    (LUCRO / VALOR_LIQUIDO) * 100,
                    2
                )
                ELSE 0
            END
        ) VIRTUAL,

    DATA_CARGA          TIMESTAMP
                        DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_FATO_VENDAS
        PRIMARY KEY (VENDA_SK),

    CONSTRAINT UK_FATO_VENDAS_PEDIDO
        UNIQUE (PEDIDO_ID, ITEM_PEDIDO),

    CONSTRAINT FK_FATO_VENDAS_TEMPO
        FOREIGN KEY (TEMPO_SK)
        REFERENCES DIM_TEMPO (TEMPO_SK),

    CONSTRAINT FK_FATO_VENDAS_CLIENTE
        FOREIGN KEY (CLIENTE_SK)
        REFERENCES DIM_CLIENTE (CLIENTE_SK),

    CONSTRAINT FK_FATO_VENDAS_PRODUTO
        FOREIGN KEY (PRODUTO_SK)
        REFERENCES DIM_PRODUTO (PRODUTO_SK),

    CONSTRAINT FK_FATO_VENDAS_VENDEDOR
        FOREIGN KEY (VENDEDOR_SK)
        REFERENCES DIM_VENDEDOR (VENDEDOR_SK),

    CONSTRAINT FK_FATO_VENDAS_CANAL
        FOREIGN KEY (CANAL_SK)
        REFERENCES DIM_CANAL (CANAL_SK),

    CONSTRAINT FK_FATO_VENDAS_STATUS
        FOREIGN KEY (STATUS_VENDA_SK)
        REFERENCES DIM_STATUS_VENDA (STATUS_VENDA_SK),

    CONSTRAINT CK_FATO_VENDAS_ITEM
        CHECK (ITEM_PEDIDO > 0),

    CONSTRAINT CK_FATO_VENDAS_QUANTIDADE
        CHECK (QUANTIDADE > 0),

    CONSTRAINT CK_FATO_VENDAS_PRECO
        CHECK (PRECO_UNITARIO >= 0),

    CONSTRAINT CK_FATO_VENDAS_DESCONTO_PCT
        CHECK (DESCONTO_PCT BETWEEN 0 AND 100),

    CONSTRAINT CK_FATO_VENDAS_VALOR_BRUTO
        CHECK (VALOR_BRUTO >= 0),

    CONSTRAINT CK_FATO_VENDAS_VALOR_DESCONTO
        CHECK (
            VALOR_DESCONTO >= 0
            AND VALOR_DESCONTO <= VALOR_BRUTO
        ),

    CONSTRAINT CK_FATO_VENDAS_VALOR_LIQUIDO
        CHECK (VALOR_LIQUIDO >= 0),

    CONSTRAINT CK_FATO_VENDAS_CUSTO
        CHECK (CUSTO_TOTAL >= 0)
);


    /* ========================================================
       REGRAS DE VALIDAÇÃO
       ======================================================== */

    CONSTRAINT CK_FATO_VENDAS_ITEM
        CHECK (ITEM_PEDIDO > 0),

    CONSTRAINT CK_FATO_VENDAS_QUANTIDADE
        CHECK (QUANTIDADE > 0),

    CONSTRAINT CK_FATO_VENDAS_PRECO
        CHECK (PRECO_UNITARIO >= 0),

    CONSTRAINT CK_FATO_VENDAS_DESCONTO_PCT
        CHECK (DESCONTO_PCT BETWEEN 0 AND 100),

    CONSTRAINT CK_FATO_VENDAS_VALOR_BRUTO
        CHECK (VALOR_BRUTO >= 0),

    CONSTRAINT CK_FATO_VENDAS_VALOR_DESCONTO
        CHECK (VALOR_DESCONTO >= 0),

    CONSTRAINT CK_FATO_VENDAS_VALOR_LIQUIDO
        CHECK (VALOR_LIQUIDO >= 0),

    CONSTRAINT CK_FATO_VENDAS_CUSTO_TOTAL
        CHECK (CUSTO_TOTAL >= 0)
);
